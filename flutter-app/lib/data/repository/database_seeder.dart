  // ── Helpers ───────────────────────────────────────────────────────────────

  Ingredient _i(
    String id,
    String name,
    IngredientCategory category,
    double kcal,
    double protein,
    double fat,
    double carbs,
    IngredientSource source,
  ) =>
      Ingredient(
        id: id,
        name: name,
        category: category,
        kcalPer100g: kcal,
        proteinPer100g: protein,
        fatPer100g: fat,
        carbsPer100g: carbs,
        source: source,
      );

  RecipeIngredient _ri(String ingredientId, double grams) =>
      RecipeIngredient(ingredientId: ingredientId, grams: grams);
}
