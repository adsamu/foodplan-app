  /// Seeds the shared Firestore collections exactly once — checked directly
  /// against Firestore (not the local cache, which starts empty on fresh install).
  Future<void> seedIfEmpty() async {
    final snap = await FirebaseFirestore.instance
        .collection('ingredients')
        .limit(1)
        .get();
    if (snap.docs.isNotEmpty) return;
    await _seedIngredients();
    await _seedRecipes();
    // Meal plan seeding is skipped — generated by the optimizer.
  }

